func (a *App) addChat(m ChatMsg) ChatMsg {
	a.chatMu.Lock()
	a.turnSeq++
	m.ID = a.turnSeq
	m.TS = time.Now().UnixMilli()
	a.chat = append(a.chat, m)
	if len(a.chat) > 400 {
		a.chat = a.chat[len(a.chat)-400:]
	}
	a.chatMu.Unlock()
	a.broadcast(map[string]any{"t": "chat", "msg": m})
	return m
}

// appendAgentText extends the trailing agent (or thinking) message.
func (a *App) appendStream(role, text string) {
	a.chatMu.Lock()
	n := len(a.chat)
	if n > 0 && a.chat[n-1].Role == role && !a.chat[n-1].Done {
		a.chat[n-1].Text += text
		m := a.chat[n-1]
		a.chatMu.Unlock()
		a.broadcast(map[string]any{"t": "chatDelta", "id": m.ID, "text": text})
		return
	}
	a.chatMu.Unlock()
	a.addChat(ChatMsg{Role: role, Text: text})
}

func (a *App) closeStream() {
	a.chatMu.Lock()
	if n := len(a.chat); n > 0 {
		a.chat[n-1].Done = true
	}
	a.chatMu.Unlock()
}

func (a *App) setBusy(b bool) {
	a.chatMu.Lock()
	a.busy = b
	a.chatMu.Unlock()
	a.broadcast(map[string]any{"t": "busy", "busy": b})
}

// UserChat sends a user message to the agent with the turn context prepended.
func (a *App) UserChat(text, selection string) {
	text = strings.TrimSpace(text)
	if text == "" {
		return
	}
	a.closeStream()
	a.addChat(ChatMsg{Role: "you", Text: text})
	if a.Agent == nil {
		a.addChat(ChatMsg{Role: "system", Text: "No agent is connected (core started with -agent none)."})
		return
	}
	msg := a.TurnContext(selection) + "\n\n" + text
	a.setBusy(true)
	if err := a.Agent.Prompt(context.Background(), msg); err != nil {
		a.addChat(ChatMsg{Role: "system", Text: "agent error: " + err.Error(), Error: true})
		a.setBusy(false)
	}
}

func (a *App) pumpAgent() {
	for ev := range a.Agent.Events() {
		switch ev.Type {
		case agent.EventDelta:
			a.appendStream("agent", ev.Text)
		case agent.EventThinking:
			a.appendStream("thinking", ev.Text)
		case agent.EventToolStart:
			a.closeStream()
			a.addChat(ChatMsg{Role: "tool", Tool: ev.Tool, CallID: ev.CallID, Args: truncate(ev.Args, 400)})
		case agent.EventToolEnd:
			a.closeStream()
			a.chatMu.Lock()
			var upd *ChatMsg
			for i := len(a.chat) - 1; i >= 0; i-- {
				if a.chat[i].Role == "tool" && a.chat[i].CallID == ev.CallID {
					a.chat[i].Result = truncate(ev.Result, 600)
					a.chat[i].Error = ev.IsError
					a.chat[i].Done = true
					c := a.chat[i]
					upd = &c
					break
				}
			}
			a.chatMu.Unlock()
			if upd != nil {
				a.broadcast(map[string]any{"t": "chatUpdate", "msg": upd})
			}
		case agent.EventTurnEnd:
			a.closeStream()
			a.setBusy(false)
			a.broadcast(map[string]any{"t": "turnEnd"})
		case agent.EventError:
			a.closeStream()
			a.addChat(ChatMsg{Role: "system", Text: ev.Text, Error: true})
			a.setBusy(false)
		}
	}
}

func truncate(s string, n int) string {
	if len(s) <= n {
		return s
	}
	return s[:n] + "…"
}

// TurnContext is everything the agent is told about the screen this turn.
// It is built only from panes whose visibility allows it.
func (a *App) TurnContext(selection string) string {
	var b strings.Builder
	b.WriteString("<nexus-context note=\"what the user's screen shows right now; generated by the app, not typed by the user\">\n")
	snap := a.Store.Snapshot()
	var spaceName string
	for _, sp := range snap.Spaces {
		if sp.ID == snap.ActiveSpace {
			spaceName = sp.Name
		}
	}
	fmt.Fprintf(&b, "space: %s (%s)\n", spaceName, snap.ActiveSpace)
	fp, hasFocus := a.Store.FocusedPane()
	panes := a.Store.Panes("")
	hidden := 0
	b.WriteString("open panes:\n")
	for _, p := range panes {
		switch p.Visibility {
		case store.VisNone:
			hidden++
			continue
		case store.VisTitle:
			fmt.Fprintf(&b, "- %s [%s] %q (content hidden from you by the user)\n", p.ID, p.Kind, p.Title)
			continue
		}
		extra := ""
		if path := str(p.Props["path"]); path != "" {
			extra = " path=" + path
		}
		if p.Pinned {
			extra += " pinned"
		}
		fmt.Fprintf(&b, "- %s [%s] %q%s\n", p.ID, p.Kind, p.Title, extra)
	}
	if hidden > 0 {
		fmt.Fprintf(&b, "(%d more pane(s) are private to the user)\n", hidden)
	}
	if hasFocus && fp.Visibility != store.VisNone {
		fmt.Fprintf(&b, "focused pane: %s %q\n", fp.ID, fp.Title)
		if fp.Visibility == store.VisFull {
			if c := a.paneExcerpt(fp); c != "" {
				b.WriteString("focused pane content (excerpt):\n")
				b.WriteString(c)
				b.WriteString("\n")
			}
		}
	}
	if selection != "" && hasFocus && fp.Visibility == store.VisFull {
		fmt.Fprintf(&b, "user's selected text: %q\n", truncate(selection, 1500))
	}
	a.pendMu.Lock()
	for _, p := range panes {
		if t := a.pluginCtx[p.ID]; t != "" && p.Visibility == store.VisFull {
			fmt.Fprintf(&b, "plugin pane %s publishes: %s\n", p.ID, truncate(t, 1500))
		}
	}
	a.pendMu.Unlock()
	b.WriteString("</nexus-context>")
	return b.String()
}

func (a *App) paneExcerpt(p store.Pane) string {
	switch p.Kind {
	case "sheet":
		sh, err := a.Sheets.Load(str(p.Props["path"]))
		if err != nil {
			return ""
		}
		return csvExcerpt(sh.Headers, sh.Rows, 25)
	case "review":
		c, err := a.Review.Content(str(p.Props["path"]))
		if err != nil {
			return ""
		}
		return truncate(c, 3000)
	case "markdown", "html":
		return truncate(str(p.Props["content"]), 2000)
	case "terminal":
		if t := a.Terms.Get(str(p.Props["term"])); t != nil {
			return t.Tail(30)
		}
	case "secure-view":
		// Only reachable if the user explicitly made this pane visible.
		if v, ok := a.Vault.Delivered(p.ID); ok {
			a.Log.Add(actionlog.Entry{Actor: "system", Action: "secure value entered agent context", Target: p.Title, Detail: "pane visibility was set to full by you"})
			return "value: " + v
		}
	}
	return ""
}

func csvExcerpt(h []string, rows [][]string, max int) string {
	var b strings.Builder
	cols := make([]string, len(h))
	for i, c := range h {
		cols[i] = fmt.Sprintf("col %d = %s", i, c)
	}
	b.WriteString("columns: " + strings.Join(cols, ", ") + "\n")
	b.WriteString("rows (row number: cells in column order):\n")
	for i, r := range rows {
		if i >= max {
			fmt.Fprintf(&b, "… %d more rows\n", len(rows)-max)
			break
		}
		fmt.Fprintf(&b, "row %d: %s\n", i, strings.Join(r, " | "))
	}
	return b.String()
}
