// Chat sends your message to an agent with that agent's turn context.
func (a *App) Chat(agentID, text, selection, view string) {
	r, err := a.run(agentID)
	if err != nil {
		a.toast(err.Error(), "error")
		return
	}
	ctx := ""
	switch r.Kind {
	case KindHome:
		ctx = a.homeContext(view)
	case KindProject:
		ctx = a.projectContext(r.Project, selection)
	case KindCustomizer:
		ctx = a.customizerContext(view, selection)
	case KindTask:
		if t, ok := a.Desk.Task(r.Task); ok {
			ctx = a.taskContext(t)
			if t.Status == "needs-input" {
				a.Desk.UpdateTask(t.ID, func(t *desk.Task) error { t.Status = "running"; return nil })
			}
		}
	}
	r.Say(text, ctx)
}

func ago(t time.Time) string {
	if t.IsZero() {
		return "never"
	}
	d := time.Since(t)
	switch {
	case d < time.Minute:
		return "just now"
	case d < time.Hour:
		return fmt.Sprintf("%dm ago", int(d.Minutes()))
	case d < 48*time.Hour:
		return fmt.Sprintf("%dh ago", int(d.Hours()))
	}
	return fmt.Sprintf("%dd ago", int(d.Hours()/24))
}

func oneLine(s string, n int) string {
	s = strings.Join(strings.Fields(s), " ")
	return truncate(s, n)
}

func briefOf(d projects.Detail) string {
	if d.Brief != "" {
		return d.Brief
	}
	return d.Readme
}

// homeContext is what the home agent is told each turn: the overview.
func (a *App) homeContext(view string) string {
	var b strings.Builder
	b.WriteString("<nexus-context note=\"generated by the app, not typed by the user\">\n")
	fmt.Fprintf(&b, "now: %s\n", time.Now().Format("Mon 2006-01-02 15:04"))
	if p, ok := a.Projects.Get(view); ok {
		fmt.Fprintf(&b, "the user is looking at project %q (%s)\n", p.Name, p.ID)
	} else {
		b.WriteString("the user is on the home dashboard\n")
	}
	ds := a.allDetails()
	if len(ds) == 0 {
		b.WriteString("projects: none yet (first run: help the user onboard; start with project_discover)\n")
	} else {
		b.WriteString("projects:\n")
		snap := a.Desk.Snapshot()
		for _, d := range ds {
			active, working := 0, 0
			for _, w := range d.Workstreams {
				if !w.Closed {
					active++
					if w.AgentStatus == "working" {
						working++
					}
				}
			}
			open := 0
			for _, bl := range d.Backlog {
				if !bl.Done {
					open++
				}
			}
			items := 0
			for _, it := range snap.Items {
				if it.Project == d.ID && it.State == "open" {
					items++
				}
			}
			needs := len(a.needsFor(d))
			fmt.Fprintf(&b, "- %s %q at %s: %s | workstreams %d (%d working), needs-you %d, backlog %d open, nexus items %d, last activity %s\n",
				d.ID, d.Name, d.Path, oneLine(briefOf(d), 140), active, working, needs, open, items, ago(d.LastActivity))
		}
	}
	waiting := 0
	for _, c := range a.Desk.Snapshot().Captures {
		if c.Status == "new" {
			waiting++
		}
	}
	if waiting > 0 {
		fmt.Fprintf(&b, "captures waiting to be filed: %d (capture_list, then capture_propose for each)\n", waiting)
	}
	if n := len(a.workNeeds()); n > 0 {
		fmt.Fprintf(&b, "tasks waiting on the user: %d (work_tasks needs_me=true)\n", n)
	}
	b.WriteString(a.describeHome())
	b.WriteString("(the user's prompt box is the chat widget; change the home screen only when asked, with home_* tools)\n")
	b.WriteString("</nexus-context>")
	return b.String()
}

// projectContext is what a project agent is told each turn.
func (a *App) projectContext(pid, selection string) string {
	p, _ := a.Projects.Get(pid)
	d, _ := a.detail(pid)
	var b strings.Builder
	b.WriteString("<nexus-context note=\"generated by the app, not typed by the user\">\n")
	fmt.Fprintf(&b, "now: %s\n", time.Now().Format("Mon 2006-01-02 15:04"))
	fmt.Fprintf(&b, "project: %q (id %s). Its folder is the file root %q (read-only for you). Write your own notes and sheets under \"desk/%s/\".\n", p.Name, p.ID, p.ID+"/", p.ID)
	if br := briefOf(d); br != "" {
		fmt.Fprintf(&b, "brief: %s\n", oneLine(br, 400))
	}
	b.WriteString(a.wikiBootstrap(pid))
	if n := len(a.pendingProposals(pid)); n > 0 {
		fmt.Fprintf(&b, "wiki proposals waiting for the user: %d\n", n)
	}
	if a.addonOn(pid, "codegraph") {
		b.WriteString("code graph: on (code_explore, code_symbols, code_symbol, code_callers, code_impact)\n")
	}
	if d.Git != nil {
		last := ""
		if len(d.Git.Commits) > 0 {
			last = fmt.Sprintf(", last commit %s %q", ago(d.Git.Commits[0].When), d.Git.Commits[0].Subject)
		}
		fmt.Fprintf(&b, "git: branch %s, %d uncommitted change(s)%s\n", d.Git.Branch, d.Git.Dirty, last)
	}
	if d.Foreman && a.addonOn(pid, "foreman") {
		n := 0
		for _, w := range d.Workstreams {
			if w.Closed {
				continue
			}
			if n == 0 {
				b.WriteString("foreman workstreams (open):\n")
			}
			n++
			if n > 10 {
				break
			}
			rep := ""
			if w.Report != "" {
				rep = " report: " + p.ID + "/" + w.Report
			}
			fmt.Fprintf(&b, "- %s [%s, report %s, %s] %s%s\n", w.Name, w.AgentStatus, w.ReportStatus, ago(w.Updated), oneLine(w.Summary, 140), rep)
		}
		var open []string
		for _, bl := range d.Backlog {
			if !bl.Done {
				open = append(open, bl.Text)
			}
		}
		if len(open) > 0 {
			fmt.Fprintf(&b, "foreman backlog: %d open; newest:\n", len(open))
			for i := len(open) - 1; i >= 0 && i >= len(open)-8; i-- {
				fmt.Fprintf(&b, "- %s\n", oneLine(open[i], 160))
			}
		}
	}
	snap := a.Desk.Snapshot()
	var items, tasks []string
	for _, it := range snap.Items {
		if it.Project == pid && it.State == "open" {
			items = append(items, fmt.Sprintf("- %s [%s] %s", it.ID, it.Kind, oneLine(it.Title, 140)))
		}
	}
	for _, t := range snap.Tasks {
		if t.Project == pid && !t.Reviewed {
			tasks = append(tasks, fmt.Sprintf("- %s [%s] %s%s", t.ID, t.Status, oneLine(t.Title, 100), map[bool]string{true: " report: " + t.Report, false: ""}[t.Report != ""]))
		}
	}
	if len(items) > 0 {
		b.WriteString("nexus items (open):\n" + strings.Join(items, "\n") + "\n")
	}
	if wi := a.describeItems(pid, false); !strings.HasPrefix(wi, "no work items") {
		b.WriteString("work items in progress (tasks: work_tasks item=<ref>):\n" + wi)
	}
	all, unshaped, pending := 0, []string{}, 0
	for _, w := range a.workItems() {
		if w.Project != pid {
			continue
		}
		all++
		if w.Unshaped {
			unshaped = append(unshaped, w.Title)
		}
	}
	for _, q := range a.openProposals() {
		if q.Project == pid {
			pending++
		}
	}
	if all == 0 && pending == 0 {
		b.WriteString("setup: this project has no work items yet (onboarding skill: project_scan, then work_propose)\n")
	}
	if pending > 0 {
		fmt.Fprintf(&b, "proposals waiting for the user's checklist: %d\n", pending)
	}
	if len(unshaped) > 0 {
		fmt.Fprintf(&b, "in progress but not shaped yet (no done-when or no tasks): %s\n", strings.Join(unshaped, "; "))
	}
	if len(tasks) > 0 {
		b.WriteString("dispatched tasks:\n" + strings.Join(tasks, "\n") + "\n")
	}
	// The screen.
	panes := a.Store.Panes(p.Space)
	if len(panes) > 0 {
		b.WriteString("open panes:\n")
	}
	for _, pn := range panes {
		if pn.Visibility == store.VisNone {
			continue // secure panes are yours alone, and the agent isn't told they exist
		}
		extra := ""
		if path := str(pn.Props["path"]); path != "" {
			extra = " path=" + path
		}
		fmt.Fprintf(&b, "- %s [%s] %q%s\n", pn.ID, pn.Kind, pn.Title, extra)
	}
	if fp, ok := a.Store.FocusedPaneIn(p.Space); ok && fp.Visibility == store.VisFull {
		fmt.Fprintf(&b, "focused pane: %s %q\n", fp.ID, fp.Title)
		if c := a.paneExcerpt(fp); c != "" {
			b.WriteString("focused pane content (excerpt):\n" + c + "\n")
		}
		if selection != "" {
			fmt.Fprintf(&b, "user's selected text: %q\n", truncate(selection, 1500))
		}
	}
	a.pendMu.Lock()
	for _, pn := range panes {
		if t := a.pluginCtx[pn.ID]; t != "" {
			fmt.Fprintf(&b, "plugin pane %s publishes: %s\n", pn.ID, truncate(t, 1500))
		}
	}
	a.pendMu.Unlock()
	b.WriteString("</nexus-context>")
	return b.String()
}

// paneExcerpt is a short view of a pane's content. Terminals are never
// included: the agent doesn't read your terminal.
func (a *App) paneExcerpt(p store.Pane) string {
	switch p.Kind {
	case "sheet":
		sh, err := a.Sheets.Load(str(p.Props["path"]))
		if err != nil {
			return ""
		}
		return csvExcerpt(sh.Headers, sh.Rows, 25)
	case "review":
		c, err := a.Review.Content(str(p.Props["path"]))
		if err != nil {
			return ""
		}
		return truncate(c, 3000)
	case "markdown", "html":
		return truncate(str(p.Props["content"]), 2000)
	case "workitem":
		ref := str(p.Props["ref"])
		for _, w := range a.workItems() {
			if w.Ref == ref {
				s := fmt.Sprintf("work item %s %q (%s, %s, move: %s)\ndone when: %s\ntasks:\n", w.Ref, w.Title, w.Source, w.State, firstNonEmpty(w.MoveNote, w.Move), strings.Join(w.DoneWhen, "; "))
				s += a.describeTasks(func(t *desk.WorkTask) bool { return t.Item == ref })
				if f := str(p.Props["task"]); f != "" {
					s += "the user has task " + f + " open\n"
				}
				return s
			}
		}
	case "task":
		if t, ok := a.Desk.Task(str(p.Props["task"])); ok {
			return fmt.Sprintf("task %s [%s] %s\nbrief:\n%s\nsummary: %s\nreport: %s", t.ID, t.Status, t.Title, truncate(t.Brief, 1500), t.Summary, t.Report)
		}
	}
	return ""
}

func csvExcerpt(h []string, rows [][]string, max int) string {
	var b strings.Builder
	cols := make([]string, len(h))
	for i, c := range h {
		cols[i] = fmt.Sprintf("col %d = %s", i, c)
	}
	b.WriteString("columns: " + strings.Join(cols, ", ") + "\n")
	b.WriteString("rows (row number: cells in column order):\n")
	for i, r := range rows {
		if i >= max {
			fmt.Fprintf(&b, "… %d more rows\n", len(rows)-max)
			break
		}
		fmt.Fprintf(&b, "row %d: %s\n", i, strings.Join(r, " | "))
	}
	return b.String()
}

