// taskContext reminds a task agent what it's working on, every turn. A
// follow-up after the task finished must not be mistaken for a new brief.
func (a *App) taskContext(t desk.Task) string {
	var b strings.Builder
	fmt.Fprintf(&b, "<task-context id=%q project=%q status=%q note=\"generated by the app\">\n", t.ID, t.Project, t.Status)
	fmt.Fprintf(&b, "Your brief (approved by the user): %s\n%s\n", t.Title, truncate(t.Brief, 4000))
	if t.Report != "" {
		fmt.Fprintf(&b, "Your report so far: %s (read it with review_read). Earlier versions: %s\n", t.Report, strings.Join(t.Reports, ", "))
	}
	switch t.Status {
	case "done", "failed", "stopped":
		b.WriteString("You already finished this task. The user is following up on it: answer about YOUR report and brief. Do not start a different task. Only revise the report if they ask; report_write saves a new version and keeps the old one.\n")
	}
	b.WriteString("</task-context>")
	return b.String()
}

func (a *App) startTask(id string) error {
	t, ok := a.Desk.Task(id)
	if !ok {
		return fmt.Errorf("no task %s", id)
	}
	if t.Status != "draft" && t.Status != "stopped" && t.Status != "failed" {
		return fmt.Errorf("task %s is %s", id, t.Status)
	}
	p, ok := a.Projects.Get(t.Project)
	if !ok {
		return fmt.Errorf("no project %s", t.Project)
	}
	a.Desk.UpdateTask(id, func(t *desk.Task) error { t.Status, t.Summary = "running", ""; return nil })
	r, err := a.run("t:" + id)
	if err != nil {
		return err
	}
	a.Log.Add(actionlog.Entry{Actor: you, Action: "dispatch task", Target: t.Title, Space: p.Space})
	d, _ := a.detail(p.ID)
	extra := ""
	if a.addonOn(p.ID, "codegraph") {
		extra = "The code graph is on: prefer code_explore / code_symbol / code_callers over reading files one by one.\n"
	}
	msg := fmt.Sprintf("<task id=%q project=%q>\nProject %q. Its folder is the file root %q (read-only for you; nothing you do changes it).\nProject brief: %s\n%s%s\nStart with plan_set. Write your report with report_write, propose wiki updates for anything durable you learned, and end with task_finish.\n</task>",
		t.ID, p.ID, p.Name, p.ID+"/", oneLine(briefOf(d), 400), a.wikiBootstrap(p.ID), extra)
	go r.Say("Brief: "+t.Title+"\n\n"+t.Brief, msg)
	return nil
}

func (a *App) taskTurnEnded(r *Run) {
	t, ok := a.Desk.Task(r.Task)
	if !ok {
		return
	}
	if r.finishing {
		r.Close()
		return
	}
	if t.Status == "running" {
		// It stopped without finishing: it's asking you something.
		a.Desk.UpdateTask(t.ID, func(t *desk.Task) error {
			t.Status, t.Summary = "needs-input", oneLine(r.lastAgentText(), 300)
			return nil
		})
		a.notifyTask(t.ID)
	}
}

func (a *App) taskFailed(r *Run, why string) {
	a.Desk.UpdateTask(r.Task, func(t *desk.Task) error {
		if t.Status == "running" || t.Status == "needs-input" {
			t.Status, t.Summary = "failed", oneLine(why, 300)
		}
		return nil
	})
	r.Close()
	a.notifyTask(r.Task)
}

func (a *App) notifyTask(id string) {
	t, ok := a.Desk.Task(id)
	if !ok {
		return
	}
	p, _ := a.Projects.Get(t.Project)
	verb := map[string]string{"done": "finished", "failed": "failed", "needs-input": "has a question", "stopped": "stopped"}[t.Status]
	if verb == "" {
		return
	}
	a.broadcast(map[string]any{"t": "notify", "text": fmt.Sprintf("%s · task %q %s", p.Name, t.Title, verb), "project": t.Project, "task": t.ID})
}

func (a *App) stopTask(id string) {
	if r := a.existingRun("t:" + id); r != nil {
		r.Abort()
		r.Close()
	}
	a.Desk.UpdateTask(id, func(t *desk.Task) error {
		if t.Status == "running" || t.Status == "needs-input" {
			t.Status, t.Summary = "stopped", "stopped by you"
		}
		return nil
	})
}
