package app

// Workstreams: every work item in progress has one, with its own agent
// (w:<ref>), conversation and context. It's derived from the item's state:
// starting an item opens it (or resumes it, with its conversation), parking
// lets it sleep, Done closes it. An idle workstream makes no model calls.
//
// The project agent is the orchestrator. Each workstream's one-line status is
// in its context every turn, and it can dig in: read a workstream's
// conversation (ws_transcript, a search or a window, like reading a file by
// line range), ask a reader that has the conversation in front of it
// (ws_ask, so a small model never parses a long transcript itself), or
// message it (ws_message, which waits for the workstream's turn to end unless
// the user interrupts). None of this is a role boundary: a workstream agent
// has the project agent's tools, and the orchestrator can do anything a
// workstream can. Only security and privacy are hard limits.

import (
	"fmt"
	"os"
	"strings"
	"time"

	"github.com/pvjammer/nexus/prototypes/desk/internal/desk"
)

const (
	KindWorkstream = "workstream" // one work item in progress, with the user
	KindAsk        = "ask"        // a throwaway reader for ws_ask: no tools, nothing kept
)

func workstreamID(ref string) string { return "w:" + ref }

// toolKind: workstream agents have the project agent's tools.
func toolKind(kind string) string {
	if kind == KindWorkstream {
		return KindProject
	}
	return kind
}

// Queued is a message waiting for an agent's turn to end.
type Queued struct {
	From string `json:"from"`
	Text string `json:"text"`
	At   int64  `json:"at"`
}

// workstreamContext is the work item a workstream agent works on, every turn.
func (a *App) workstreamContext(r *Run) string {
	w, err := a.checkItemRef(r.Item)
	if err != nil {
		return fmt.Sprintf("<workstream item=%q>This work item isn't listed any more. Tell the user.</workstream>", r.Item)
	}
	var b strings.Builder
	fmt.Fprintf(&b, "<workstream item=%q title=%q note=\"generated by the app\">\n", w.Ref, w.Title)
	b.WriteString("You are this work item's agent: you work on it with the user, in its own conversation. The project agent orchestrates the project and may message you; answer it in your reply.\n")
	fmt.Fprintf(&b, "state: %s · whose move: %s\n", w.State, firstNonEmpty(w.MoveNote, w.Move))
	if w.Brief != "" {
		fmt.Fprintf(&b, "brief: %s\n", oneLine(w.Brief, 500))
	}
	if len(w.DoneWhen) > 0 {
		fmt.Fprintf(&b, "done when: %s\n", strings.Join(w.DoneWhen, "; "))
	} else {
		b.WriteString("done when: not set yet (shape it: ask the user, then work_item_set done_when)\n")
	}
	b.WriteString("tasks:\n" + a.describeTasks(func(t *desk.WorkTask) bool { return t.Item == w.Ref && t.Status != "done" }))
	if w.Claimed != "" {
		b.WriteString("You (or an agent) told the user it looks done; they haven't confirmed yet.\n")
	}
	b.WriteString("When every done-when check is met, say so with work_item_set state done and evidence: the user confirms.\n")
	b.WriteString("</workstream>")
	return b.String()
}

// workstreamLines is each workstream's status, for the orchestrator.
func (a *App) workstreamLines(pid string) string {
	var b strings.Builder
	n := 0
	for _, w := range a.workItems() {
		if w.Project != pid || w.State != "in-progress" {
			continue
		}
		n++
		activity := "no conversation yet"
		if r := a.existingRun(workstreamID(w.Ref)); r != nil {
			hist, busy := r.history()
			for i := len(hist) - 1; i >= 0; i-- {
				if m := hist[i]; m.Role == "agent" && strings.TrimSpace(m.Text) != "" {
					activity = fmt.Sprintf("last said %s: %q", ago(time.UnixMilli(m.TS)), oneLine(m.Text, 90))
					break
				}
			}
			if busy {
				activity = "working now; " + activity
			}
			if len(r.queuedMsgs()) > 0 {
				activity += fmt.Sprintf(" · %d message(s) waiting for its turn", len(r.queuedMsgs()))
			}
		}
		next := ""
		if t := a.nextTask(w.Ref); t != nil {
			next = fmt.Sprintf(" · next: %q (%s)", t.Title, t.Assignee)
		}
		fmt.Fprintf(&b, "- %q (agent w:%s) · %s%s · %s\n", w.Title, w.Ref, firstNonEmpty(w.MoveNote, w.Move), next, activity)
	}
	if n == 0 {
		return ""
	}
	return "workstreams (one agent per work item in progress; ws_transcript reads one's conversation, ws_ask asks it a question, ws_message tells it something):\n" + b.String()
}

// nextTask is the work item's next open task: yours first, then the agent's,
// then anyone's.
func (a *App) nextTask(ref string) *desk.WorkTask {
	var mine, ag, any *desk.WorkTask
	for _, t := range a.Desk.Snapshot().WorkTasks {
		if t.Item != ref || t.Status == "done" {
			continue
		}
		switch {
		case needsMe(t) && mine == nil:
			mine = t
		case agentOn(t) && ag == nil:
			ag = t
		case any == nil:
			any = t
		}
	}
	for _, t := range []*desk.WorkTask{mine, ag, any} {
		if t != nil {
			return t
		}
	}
	return nil
}

// ---- reading a conversation ----

// chatOf is an agent's saved conversation, running or not.
func (a *App) chatOf(id string) []ChatMsg {
	if r := a.existingRun(id); r != nil {
		h, _ := r.history()
		return h
	}
	m, _ := a.loadChat(id)
	return m
}

func msgLine(i int, m ChatMsg, n int) string {
	switch m.Role {
	case "thinking":
		return ""
	case "tool":
		res := oneLine(m.Result, n/2)
		if m.Error {
			res = "error: " + res
		}
		return fmt.Sprintf("#%d [tool %s] %s → %s", i, m.Tool, oneLine(m.Args, n/2), res)
	}
	return fmt.Sprintf("#%d %s: %s", i, m.Role, oneLine(m.Text, n))
}

// transcriptWindow is a search or a window of a conversation, always saying
// how much there is and how to get more.
func transcriptWindow(msgs []ChatMsg, query string, from, count int) string {
	total := len(msgs)
	if total == 0 {
		return "no conversation yet"
	}
	if count <= 0 || count > 40 {
		count = 20
	}
	var b strings.Builder
	if q := strings.ToLower(strings.TrimSpace(query)); q != "" {
		hits := 0
		for i, m := range msgs {
			if !strings.Contains(strings.ToLower(m.Text+" "+m.Args+" "+m.Result), q) {
				continue
			}
			if l := msgLine(i+1, m, 300); l != "" {
				if hits == count {
					fmt.Fprintf(&b, "… more matches: search for something narrower, or read a window with from=<#>\n")
					break
				}
				b.WriteString(l + "\n")
				hits++
			}
		}
		if hits == 0 {
			return fmt.Sprintf("no message matches %q (%d messages). Try another word, or read the newest with no query.", query, total)
		}
		fmt.Fprintf(&b, "(%d messages in all; from=<#> reads the messages around a match)\n", total)
		return b.String()
	}
	if from <= 0 {
		from = max(1, total-count+1)
	}
	to := min(total, from+count-1)
	for i := from; i <= to; i++ {
		if l := msgLine(i, msgs[i-1], 400); l != "" {
			b.WriteString(l + "\n")
		}
	}
	fmt.Fprintf(&b, "(messages %d-%d of %d", from, to, total)
	if from > 1 {
		fmt.Fprintf(&b, "; from=%d for the %d before", max(1, from-count), min(count, from-1))
	}
	if to < total {
		fmt.Fprintf(&b, "; from=%d for the next", to+1)
	}
	b.WriteString(")\n")
	return b.String()
}

// transcriptText is a conversation as plain text for a reader, newest kept
// when it's too long.
func transcriptText(msgs []ChatMsg, maxChars int) string {
	var lines []string
	size := 0
	for i := len(msgs) - 1; i >= 0; i-- {
		l := msgLine(i+1, msgs[i], 1200)
		if l == "" {
			continue
		}
		if size+len(l) > maxChars {
			lines = append(lines, fmt.Sprintf("(%d earlier messages left out)", i+1))
			break
		}
		size += len(l)
		lines = append(lines, l)
	}
	for i, j := 0, len(lines)-1; i < j; i, j = i+1, j-1 {
		lines[i], lines[j] = lines[j], lines[i]
	}
	return strings.Join(lines, "\n")
}

// ---- asking a reader ----

// turnWaiter returns a channel closed when the agent's current turn ends.
func (r *Run) turnWaiter() chan struct{} {
	ch := make(chan struct{})
	r.mu.Lock()
	r.waiters = append(r.waiters, ch)
	r.mu.Unlock()
	return ch
}

// askReader gives a throwaway agent a conversation and a question, and waits
// for its answer. The reader has no tools and is discarded afterwards; the
// workstream's own conversation doesn't move.
func (a *App) askReader(project, title string, msgs []ChatMsg, question, from string) (string, error) {
	if a.cfg.Agents == nil {
		return "", fixErr("ws_ask needs an agent loop (this core has none); use ws_transcript")
	}
	id := "ask:" + newToken()[:10]
	r, err := a.run(id)
	if err != nil {
		return "", err
	}
	r.Project = project
	defer a.forgetRun(r)
	prompt := fmt.Sprintf("<conversation workstream=%q>\n%s\n</conversation>\n\nThe %s asks about this workstream: %s\n\nAnswer in a few lines, only from the conversation above. If it doesn't say, say that.",
		title, transcriptText(msgs, 60000), from, question)
	done := r.turnWaiter()
	if err := r.sayAs("app", prompt, ""); err != nil {
		return "", err
	}
	select {
	case <-done:
	case <-time.After(4 * time.Minute):
		return "", fmt.Errorf("the reader took too long; use ws_transcript")
	}
	ans := r.finalText()
	if ans == "" {
		return "", fmt.Errorf("the reader gave no answer; use ws_transcript")
	}
	return ans, nil
}

func (a *App) forgetRun(r *Run) {
	r.Close()
	a.runMu.Lock()
	if a.runs[r.ID] == r {
		delete(a.runs, r.ID)
	}
	a.runMu.Unlock()
	os.Remove(a.chatPath(r.ID))
}

// ---- messages that wait for the turn to end ----

func (r *Run) isBusy() bool {
	r.mu.Lock()
	defer r.mu.Unlock()
	return r.busy
}

func (r *Run) queuedMsgs() []Queued {
	r.mu.Lock()
	defer r.mu.Unlock()
	return append([]Queued(nil), r.queue...)
}

// deliver sends a message from someone other than the user (another agent,
// or the app on the user's behalf): now if the agent is free, else when its
// turn ends. It reports whether it was queued.
func (a *App) deliver(r *Run, from, text string) bool {
	r.mu.Lock()
	if r.busy {
		r.queue = append(r.queue, Queued{From: from, Text: text, At: time.Now().UnixMilli()})
		r.mu.Unlock()
		a.broadcastDesk()
		return true
	}
	r.mu.Unlock()
	go r.sayAs("app", messageText(from, text), a.contextFor(r, "", ""))
	return false
}

func messageText(from, text string) string {
	if from == "" || from == "app" {
		return text
	}
	return fmt.Sprintf("Message from the %s: %s", from, text)
}

// turnEnded runs when any agent's turn ends: wake ws_ask waiters, note what
// was true (for the next "since your last turn"), and hand it the next
// waiting message.
func (r *Run) turnEnded() {
	r.mu.Lock()
	ws := r.waiters
	r.waiters = nil
	var next *Queued
	if len(r.queue) > 0 {
		q := r.queue[0]
		r.queue = r.queue[1:]
		next = &q
	}
	r.mu.Unlock()
	for _, ch := range ws {
		close(ch)
	}
	if r.Kind == KindProject || r.Kind == KindWorkstream {
		r.a.markTurn(r)
	}
	switch {
	case r.Kind == KindHome:
		r.a.maybeEndEpisode(r, false)
	case r.Kind == KindCustomizer && next == nil && r.a.episodePending(r) == "":
		// a small change went live (or it only answered): that request is settled
		r.a.endEpisode(r, "")
	}
	if next != nil {
		r.a.broadcastDesk()
		go r.sayAs("app", messageText(next.From, next.Text), r.a.contextFor(r, "", ""))
	}
}

// interrupt is the user cutting in: stop the turn, so the waiting message
// goes now.
func (a *App) interrupt(id string) error {
	r := a.existingRun(id)
	if r == nil {
		return fixErr("no agent %s", id)
	}
	if !r.isBusy() {
		if len(r.queuedMsgs()) > 0 {
			r.turnEnded()
		}
		return nil
	}
	r.Abort()
	go func() { // a loop that doesn't report the aborted turn still gets the message
		time.Sleep(3 * time.Second)
		if !r.isBusy() && len(r.queuedMsgs()) > 0 {
			r.turnEnded()
		}
	}()
	return nil
}

func (a *App) queues() map[string][]Queued {
	out := map[string][]Queued{}
	for _, r := range a.allRuns() {
		if q := r.queuedMsgs(); len(q) > 0 {
			out[r.ID] = q
		}
	}
	return out
}

// ---- hand-off ----

// handOff gives a task of yours to the agent of its workstream (or the
// project agent for a todo), which does it and moves it to review.
func (a *App) handOff(id string) (desk.WorkTask, error) {
	t, err := a.findTask(id)
	if err != nil {
		return t, err
	}
	agent, ws := a.agentFor(t)
	if agent == "" {
		return t, fixErr("this todo has no project, so there's no agent to hand it to. Give it a project first")
	}
	ag, st := "agent", "doing"
	nt, err := a.workTaskUpdate("you", "", t.ID, TaskEdit{Assignee: &ag, Status: &st, Why: "handed to the agent"})
	if err != nil {
		return nt, err
	}
	r, err := a.run(agent)
	if err != nil {
		return nt, err
	}
	where := ""
	if ws {
		where = " It's on your work item."
	}
	msg := fmt.Sprintf("The user handed you a task: %q (id %s).%s Do it now with your tools. When it's done, move it to review: work_task_update status review, with a note saying what you did and where to look. If you can't do it, say why and give it back (assignee you).", nt.Title, nt.ID, where)
	a.deliver(r, "app", msg)
	return nt, nil
}

// agentFor is who works on a task: its workstream's agent when its work item
// is in progress, else its project's agent.
func (a *App) agentFor(t desk.WorkTask) (string, bool) {
	if t.Item != "" {
		if w, err := a.checkItemRef(t.Item); err == nil && w.State == "in-progress" {
			return workstreamID(w.Ref), true
		}
	}
	if t.Project != "" {
		return "p:" + t.Project, false
	}
	return "", false
}

// ---- tools ----

func (a *App) workstreamTools() []Tool {
	item := sprop("work item ref or exact title (see the workstreams in your context)")
	find := func(c *Ctx, m map[string]any) (WorkItem, error) {
		w, err := a.checkItemRef(sArg(m, "item"))
		if err != nil {
			return w, err
		}
		if c.inProject() && w.Project != c.Project.ID {
			return w, deny("work item %s is in project %s, not yours (%s)", w.Ref, w.Project, c.Project.ID)
		}
		return w, nil
	}
	return []Tool{
		{Name: "ws_transcript", Label: "Read a workstream", Kinds: HPT,
			Description: "Read a workstream's conversation with the user: the newest messages, a window (from=<#>), or the messages matching a word (query). Each result says how much there is and how to get more. To ask what it says (where it stands, why it decided something), ws_ask is usually quicker.",
			Parameters: obj([]string{"item"}, map[string]any{
				"item": item, "query": sprop("a word or phrase to find (optional)"), "from": iprop("message number to start at (optional; default the newest)"), "count": iprop("how many messages (default 20, at most 40)"),
			}),
			run: func(a *App, c *Ctx, m map[string]any) (string, error) {
				w, err := find(c, m)
				if err != nil {
					return "", err
				}
				return fmt.Sprintf("workstream %q:\n", w.Title) + transcriptWindow(a.chatOf(workstreamID(w.Ref)), sArg(m, "query"), iArg(m, "from", 0), iArg(m, "count", 20)), nil
			}},
		{Name: "ws_ask", Label: "Ask about a workstream", Kinds: HP,
			Description: "Ask a question about a workstream (\"where does it stand?\", \"why did it pick Postgres?\"). A reader with its whole conversation answers in a few lines; the workstream itself isn't disturbed. Takes up to a minute or two.",
			Parameters:  obj([]string{"item", "question"}, map[string]any{"item": item, "question": sprop("what you want to know")}),
			run: func(a *App, c *Ctx, m map[string]any) (string, error) {
				w, err := find(c, m)
				if err != nil {
					return "", err
				}
				msgs := a.chatOf(workstreamID(w.Ref))
				if len(msgs) == 0 {
					return fmt.Sprintf("%q has no conversation yet. Its brief, done-when and tasks are what there is (work_tasks item=%s).", w.Title, w.Ref), nil
				}
				ans, err := a.askReader(w.Project, w.Title, msgs, sArg(m, "question"), c.Run.label())
				if err != nil {
					return "", err
				}
				return fmt.Sprintf("About %q (from its conversation):\n%s", w.Title, ans), nil
			}},
		{Name: "ws_message", Label: "Message a workstream", Kinds: HP,
			Description: "Tell a workstream's agent something, or ask it to do something. If it's mid-turn, your message waits until the turn ends (the user can interrupt). Its reply is in its own conversation: read it later with ws_transcript.",
			Parameters:  obj([]string{"item", "text"}, map[string]any{"item": item, "text": sprop("the message")}),
			run: func(a *App, c *Ctx, m map[string]any) (string, error) {
				w, err := find(c, m)
				if err != nil {
					return "", err
				}
				if w.State != "in-progress" {
					return "", fixErr("%q isn't in progress (%s), so its workstream is asleep. Start it first, or ask the user", w.Title, w.State)
				}
				if c.Run.ID == workstreamID(w.Ref) {
					return "", fixErr("that's your own workstream")
				}
				r, err := a.run(workstreamID(w.Ref))
				if err != nil {
					return "", err
				}
				if a.deliver(r, c.Run.label(), sArg(m, "text")) {
					return fmt.Sprintf("Queued: the %q agent is mid-turn and gets your message when the turn ends. The user can interrupt it instead.", w.Title), nil
				}
				return fmt.Sprintf("Sent to the %q agent. Its reply is in its own conversation (ws_transcript item=%s).", w.Title, w.Ref), nil
			}},
		{Name: "project_changes", Label: "What changed", Kinds: P,
			Description: "Everything that changed in your project since your last turn: tasks and work items (and who changed them), and the project folder (files edited, added or deleted, commits, branch). Your turn context has the short version.",
			Parameters:  obj(nil, map[string]any{}),
			run: func(a *App, c *Ctx, m map[string]any) (string, error) {
				if s := a.sinceLastTurn(c.Run, 0); s != "" {
					return s, nil
				}
				return "nothing changed since your last turn (or this is your first turn since Nexus started)", nil
			}},
	}
}
